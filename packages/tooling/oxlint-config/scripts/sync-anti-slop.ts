// Copies the anti-slop Oxlint plugin into src/vendor/anti-slop. Files stay verbatim apart from a banner, so a new
// upstream revision can be taken by rerunning this script. Usage: pnpm sync:anti-slop [commit]
import { createHash } from "node:crypto"
import { mkdirSync, rmSync, writeFileSync } from "node:fs"
import { dirname, posix, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const packageRoot = fileURLToPath(new URL("../", import.meta.url))
const vendorRoot = resolve(packageRoot, "src/vendor/anti-slop")
const repository = "dmmulroy/anti-slop"

// The generic rules. The Effect rule group only applies to apps built on Effect, and tests stay upstream.
const isVendored = (path: string) =>
  path.startsWith("src/") && !path.startsWith("src/effect/") && !path.endsWith(".test.ts")

// Packages the vendored files may import. Everything else must be vendored or a Node built-in.
const packages = new Set(["@oxlint/plugins"])

async function get(url: string) {
  const response = await fetch(url, { headers: { "User-Agent": "buildkit-anti-slop-sync" } })
  if (!response.ok) {
    throw new Error(`${response.status}: ${url}`)
  }
  return response
}

const hash = (text: string) => createHash("sha256").update(text.replaceAll("\r\n", "\n")).digest("hex")

const commit = process.argv[2] ?? "main"
const { sha: revision } = (await (
  await get(`https://api.github.com/repos/${repository}/commits/${commit}`)
).json()) as {
  sha: string
}
const { tree } = (await (
  await get(`https://api.github.com/repos/${repository}/git/trees/${revision}?recursive=1`)
).json()) as { tree: { path: string; type: string }[] }
const files = tree
  .filter((entry) => entry.type === "blob" && isVendored(entry.path))
  .map((entry) => entry.path)
  .sort()
const raw = async (path: string) =>
  (await get(`https://raw.githubusercontent.com/${repository}/${revision}/${path}`)).text()

function checkImports(path: string, text: string) {
  const statements = /^\s*(?:import|export)\s[^;]*?\bfrom\s*["']([^"']+)["']|^\s*import\s*["']([^"']+)["']/gm
  for (const [, from, sideEffect] of text.matchAll(statements)) {
    const specifier = from ?? sideEffect
    if (!specifier || specifier.startsWith("node:") || packages.has(specifier)) {
      continue
    }
    if (!specifier.startsWith(".") || !files.includes(posix.join(posix.dirname(path), specifier))) {
      throw new Error(`${path} imports ${specifier}, which is not vendored. Vendor it or allow the package.`)
    }
  }
}

// Everything is fetched and checked before any file is written, so a failed sync leaves the previous one in place.
// Generated files such as README.md have no upstream hash.
const outputs: Record<string, string> = {}
const snapshotFiles: Record<string, { upstream?: string; vendored: string }> = {}
for (const path of files) {
  const upstream = await raw(path)
  const target = path.slice("src/".length)
  const isSource = path.endsWith(".ts")
  if (isSource) {
    checkImports(path, upstream)
  }
  outputs[target] = isSource
    ? `// Vendored from anti-slop ${revision.slice(0, 7)} (${path}). Do not edit. Run pnpm sync:anti-slop instead.\n${upstream}`
    : upstream
  snapshotFiles[target] = { upstream: hash(upstream), vendored: hash(outputs[target]) }
}
if (!outputs["index.ts"]) {
  throw new Error("Upstream no longer has src/index.ts. Review its layout and update this script.")
}
const license = await raw("LICENSE")
outputs.LICENSE = license
snapshotFiles.LICENSE = { upstream: hash(license), vendored: hash(license) }
outputs["README.md"] = `# Vendored anti-slop source

Generated by \`pnpm sync:anti-slop\` from [anti-slop](https://github.com/${repository}/tree/${revision}) at
${revision}. Do not edit these files. Change the sync script or the presets in \`src/\`, then rerun it. See
[the vendoring guide](../../../docs/anti-slop.md).
`
snapshotFiles["README.md"] = { vendored: hash(outputs["README.md"]) }

rmSync(vendorRoot, { recursive: true, force: true })
for (const [path, text] of Object.entries(outputs)) {
  mkdirSync(dirname(resolve(vendorRoot, path)), { recursive: true })
  writeFileSync(resolve(vendorRoot, path), text)
}
writeFileSync(
  resolve(vendorRoot, "snapshot.json"),
  JSON.stringify({ repository: `https://github.com/${repository}`, revision, files: snapshotFiles }, null, 2) + "\n"
)

process.stdout.write(`Vendored anti-slop ${revision}: ${files.length} files.\n`)
